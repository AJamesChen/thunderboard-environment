package com.jamesc.bg22monitor;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;
import java.util.zip.CRC32;
import java.util.zip.ZipEntry;
import java.util.zip.ZipInputStream;

/** Parses a .bg22ota ZIP without extracting files into the filesystem. */
public final class OtaImage {
    public static final String BOARD = "BRD4184A-A02";
    public static final int SLOT_SIZE = 196608;
    public final byte[] bytes;
    public final long version;
    public final String sha256;

    private OtaImage(byte[] bytes, long version, String sha256) {
        this.bytes = bytes; this.version = version; this.sha256 = sha256;
    }

    public static OtaImage read(InputStream input) throws IOException {
        if (input == null) throw new IOException("Cannot open update file");
        Map<String, byte[]> entries = new HashMap<>();
        try (ZipInputStream zip = new ZipInputStream(input)) {
            ZipEntry entry;
            while ((entry = zip.getNextEntry()) != null) {
                String name = entry.getName();
                if (!name.equals("manifest.properties") && !name.equals("application.gbl"))
                    throw new IOException("Unexpected file in update package: " + name);
                if (entries.containsKey(name)) throw new IOException("Duplicate update package entry");
                int limit = name.endsWith(".gbl") ? SLOT_SIZE : 4096;
                ByteArrayOutputStream out = new ByteArrayOutputStream();
                byte[] buffer = new byte[4096];
                int n;
                while ((n = zip.read(buffer)) != -1) {
                    if (out.size() + n > limit) throw new IOException("Update package exceeds board capacity");
                    out.write(buffer, 0, n);
                }
                entries.put(name, out.toByteArray());
            }
        }
        if (entries.size() != 2) throw new IOException("Choose a .bg22ota update package generated by build.py");
        // Use a deliberately small, strict manifest rather than trusting a filename.
        Map<String, String> manifest = new HashMap<>();
        for (String line : new String(entries.get("manifest.properties"), StandardCharsets.UTF_8).split("\n")) {
            if (line.isBlank()) continue;
            int split = line.indexOf('=');
            if (split < 1 || manifest.put(line.substring(0, split), line.substring(split + 1).trim()) != null)
                throw new IOException("Invalid update manifest");
        }
        if (!"1".equals(manifest.get("format")) || !BOARD.equals(manifest.get("board")))
            throw new IOException("This package is not for Thunderboard BRD4184A revision A02");
        byte[] gbl = entries.get("application.gbl");
        long version;
        try {
            version = Long.parseLong(manifest.getOrDefault("version", ""));
            if (version < 1 || version > 0xffffffffL) throw new NumberFormatException();
            if (Integer.parseInt(manifest.getOrDefault("size", "")) != gbl.length) throw new NumberFormatException();
        } catch (NumberFormatException e) { throw new IOException("Invalid firmware version or size", e); }
        String checksum = hex(digest(gbl));
        if (!checksum.equals(manifest.get("sha256"))) throw new IOException("Firmware checksum does not match");
        validateGbl(gbl, version);
        return new OtaImage(gbl, version, checksum);
    }

    private static void validateGbl(byte[] bytes, long expectedVersion) throws IOException {
        if (bytes.length < 32 || bytes.length > SLOT_SIZE) throw new IOException("Invalid GBL size");
        ByteBuffer b = ByteBuffer.wrap(bytes).order(ByteOrder.LITTLE_ENDIAN);
        if (b.getInt(0) != 0x03a617eb) throw new IOException("Invalid GBL header");
        boolean application = false, program = false, end = false;
        int offset = 0;
        while (offset + 8 <= bytes.length) {
            int tag = b.getInt(offset);
            long length = Integer.toUnsignedLong(b.getInt(offset + 4));
            long next = offset + 8L + length;
            if (next > bytes.length) throw new IOException("Truncated GBL tag");
            if (tag == 0xf40a0af4) {
                if (length != 28 || application) throw new IOException("Invalid application metadata");
                long version = Integer.toUnsignedLong(b.getInt(offset + 12));
                byte[] product = Arrays.copyOfRange(bytes, offset + 20, offset + 36);
                if (version != expectedVersion || !Arrays.equals(product, "BG22ENV-BRD4184A".getBytes(StandardCharsets.US_ASCII)))
                    throw new IOException("GBL firmware version or product ID does not match this board");
                application = true;
            } else if (tag == 0xf50909f5 || tag == 0x5ea617eb) {
                throw new IOException("Only application firmware updates are supported");
            }
            // Standard uncompressed program and erase/program records.
            if (tag == 0xfe0101fe || tag == 0xfd0303fd) {
                if (length < 4) throw new IOException("Empty application program tag");
                long address = Integer.toUnsignedLong(b.getInt(offset + 8));
                if (address < 0x6000L || address + length - 4 > 0x44000L)
                    throw new IOException("Application overlaps the bootloader or update slot");
                program = true;
            } else if (tag != 0x03a617eb && tag != 0xf40a0af4 && tag != 0xfc0404fc) {
                throw new IOException("Unsupported GBL tag; use an uncompressed application package");
            }
            if (tag == 0xfc0404fc) {
                if (length != 4 || next != bytes.length) throw new IOException("Invalid GBL end tag");
                end = true;
            }
            offset = (int)next;
        }
        CRC32 crc = new CRC32(); crc.update(bytes);
        if (offset != bytes.length || !application || !program || !end || crc.getValue() != 0x2144df1cL)
            throw new IOException("Invalid or incomplete GBL application image");
    }

    private static byte[] digest(byte[] bytes) throws IOException {
        try { return MessageDigest.getInstance("SHA-256").digest(bytes); }
        catch (NoSuchAlgorithmException e) { throw new IOException(e); }
    }
    private static String hex(byte[] bytes) {
        StringBuilder result = new StringBuilder();
        for (byte value : bytes) result.append(String.format(java.util.Locale.ROOT, "%02x", value & 255));
        return result.toString();
    }
}
